/**
 * 상태 문자열 다국어 변환 헬퍼
 */
export function formatReadingStatus(status, isEn) {
  if (!status) return isEn ? 'To Read' : '시작전';
  const s = String(status).trim();
  if (s === 'PLANNED' || s === '시작전' || s === '시작 전') {
    return isEn ? 'To Read' : '시작전';
  }
  if (s === 'READING' || s === '읽는 중' || s === '읽는중') {
    return isEn ? 'Reading' : '읽는 중';
  }
  if (s === 'COMPLETED' || s === '완독') {
    return isEn ? 'Completed' : '완독';
  }
  if (s === 'PAUSED' || s === '잠시 멈춤') {
    return isEn ? 'Paused' : '잠시 멈춤';
  }
  return status;
}

/**
 * 장르 코드/라벨 다국어 변환 헬퍼
 */
export function formatGenre(genreCodeOrLabel, isEn) {
  if (!genreCodeOrLabel) return isEn ? 'Unspecified' : '미지정';
  const g = String(genreCodeOrLabel).trim();
  const dict = translations[isEn ? 'en' : 'ko'].genre;

  // code로 매칭
  if (dict[g]) return dict[g];

  // 한국어 라벨로 매칭
  const koGenre = translations.ko.genre;
  for (const [code, label] of Object.entries(koGenre)) {
    if (label === g) {
      return dict[code] || label;
    }
  }

  return genreCodeOrLabel;
}
